'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(x=>x[1]).filter(x=>x.trim());
assert(inline.length>0,'No inline script');
inline.forEach((js,i)=>new vm.Script(js,{filename:'index.html:script'+(i+1)}));
assert(html.includes('id="url"'),'URL field missing');
assert(html.includes('id="run"'),'Analyze button missing');
assert(html.includes('id="result"'),'Results container missing');
assert(html.includes('/api/check'),'Check API missing');
assert(!html.includes('id="screens"'),'Screenshot upload should not be required');
assert(!html.includes('tesseract.min.js'),'OCR should not be required');
console.log('Geonode-powered page script parsed and link workflow verified');
